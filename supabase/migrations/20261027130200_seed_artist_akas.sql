-- Stop if a name has changed since the review, instead of skipping it
do $$
declare
  missing text;
begin
  select string_agg(n, ', ') into missing
  from (
    select aka as n from seed_akas union select canonical from seed_akas
    union select artist from seed_rejections union select other_artist from seed_rejections
  ) names
  where not exists (select 1 from artists a where a.name = names.n);

  if missing is not null then
    raise exception 'These artists no longer exist under these names: %', missing;
  end if;
end;
$$;

update artists a
set canonical_artist_id = c.id
from seed_akas s
join artists c on c.name = s.canonical
where a.name = s.aka;

insert into artist_aka_rejections (artist_id, other_artist_id)
select least(x.id, y.id), greatest(x.id, y.id)
from seed_rejections s
join artists x on x.name = s.artist
join artists y on y.name = s.other_artist
on conflict do nothing;

drop table seed_akas, seed_rejections;
